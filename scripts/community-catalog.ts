// Reference-only catalog: discovery JSON remains canonical. No environment or cloud access.
import { readFileSync, writeFileSync } from 'node:fs';
const source = JSON.parse(readFileSync('public/data/markets.geojson', 'utf8')) as {
  features: {
    properties: { id: string; name: string; city: string; state: string };
    geometry: { coordinates: number[] };
  }[];
};
const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;
const rows = source.features
  .sort((a, b) => a.properties.id.localeCompare(b.properties.id))
  .map(
    ({ properties: p, geometry: g }) =>
      `(${[p.id, p.name, p.city, p.state].map(quote).join(',')},${g.coordinates[1]},${g.coordinates[0]})`,
  );
const sql = `-- Generated by scripts/community-catalog.ts from existing discovery IDs. Reference metadata only.\nbegin;\ninsert into public.community_market_catalog(source_id,name,city,state,lat,lng) values\n${rows.join(',\n')}\non conflict(source_id) do nothing;\ncommit;\n`;
writeFileSync('supabase/migrations/202610180002_discovery_references.sql', sql);
console.log(`Prepared ${rows.length} existing market references; no cloud writes.`);
